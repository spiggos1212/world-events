// Ήπειροι: πρόχειρα πολύγωνα (lng, lat) για την κατάταξη κάθε γεγονότος σε ήπειρο
// και το πλαίσιο (bbox) στο οποίο κάνει zoom ο χάρτης όταν επιλεγεί η ήπειρος.
// Τα σύνορα ακολουθούν τη συνηθισμένη σύμβαση: Ουράλια / Κασπία / Καύκασος / Βόσπορος για Ευρώπη–Ασία,
// Σουέζ / Ερυθρά Θάλασσα για Αφρική–Ασία, Παναμάς για Βόρεια–Νότια Αμερική.
(function () {
  const EUROPE = [
    [-25, 82], [62, 82], [62, 56], [60, 50], [48, 47], [40, 43], [41.5, 41.5], [29.2, 40.9], [26.75, 40.42], [26.2, 40.02],
    [26.5, 39.0], [27.1, 37.9], [27.4, 37.2], [28.3, 36.4], [29, 35.5], [24, 34.5], [15, 35.5], [12, 36.2], [9, 37.6],
    [0, 36.5], [-5.5, 36], [-6, 35.9], [-25, 35.5],
  ];
  const AFRICA = [
    [-25, 35.5], [-6, 35.9], [-5.5, 36], [0, 36.5], [9, 37.6], [12, 36.2], [15, 35.5], [24, 34.5], [29, 35.5], [32.3, 31.3],
    [32.6, 29.9], [34, 27.5], [43, 12.5], [51, 11], [60, 8], [60, -60], [-25, -60],
  ];
  const NAMERICA = [
    [-170, 85], [-15, 85], [-15, 70], [-30, 60], [-30, 11.5], [-60, 11.5], [-70, 12.8], [-77, 12.8], [-77.3, 8], [-78, 7], [-82, 7], [-120, 7], [-120, 30], [-180, 50], [-180, 85],
  ];
  const SAMERICA = [[-30, 11.5], [-60, 11.5], [-70, 12.8], [-77, 12.8], [-77.3, 8], [-78, 7], [-82, 7], [-95, 0], [-100, -15], [-100, -60], [-30, -60]];
  const OCEANIA_A = [[110, -60], [110, -12], [128, -12], [131, -5], [131, 8], [140, 8], [140, 30], [180, 30], [180, -60]];
  const OCEANIA_B = [[-180, 30], [-120, 30], [-120, -15], [-100, -15], [-100, -60], [-180, -60]];

  function inPoly(p, poly) {
    const [x, y] = p;
    let inside = false;
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [xi, yi] = poly[i], [xj, yj] = poly[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
    return inside;
  }

  // Σειρά ελέγχου: πρώτα οι «μικρές» ήπειροι, η Ασία είναι ό,τι απομένει στο ανατολικό ημισφαίριο.
  const ORDER = [
    ["oceania", [OCEANIA_A, OCEANIA_B]],
    ["africa", [AFRICA]],
    ["namerica", [NAMERICA]],
    ["samerica", [SAMERICA]],
    ["europe", [EUROPE]],
  ];
  function classify(lng, lat) {
    const p = [lng, lat];
    for (const [key, polys] of ORDER) if (polys.some((poly) => inPoly(p, poly))) return key;
    if (lat < -60) return null; // Ανταρκτική
    if (lng >= 25 || lng < -168) return "asia";
    return null;
  }

  // Πλαίσιο zoom [[lng0, lat0], [lng1, lat1]] και ετικέτες
  const LIST = [
    { key: "europe", el: "Ευρώπη", en: "Europe", bbox: [[-12, 35], [45, 71]] },
    { key: "asia", el: "Ασία", en: "Asia", bbox: [[26, -10], [150, 70]] },
    { key: "africa", el: "Αφρική", en: "Africa", bbox: [[-20, -36], [52, 38]] },
    { key: "namerica", el: "Βόρεια Αμερική", en: "North America", bbox: [[-168, 7], [-50, 75]] },
    { key: "samerica", el: "Νότια Αμερική", en: "South America", bbox: [[-85, -56], [-33, 13]] },
    { key: "oceania", el: "Ωκεανία", en: "Oceania", bbox: [[110, -50], [180, 10]] },
  ];

  window.WORLD_CONTINENTS = { list: LIST, classify };
})();
